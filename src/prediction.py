def get_default_model_path() -> Path:
    """Return default path to the saved final model pipeline."""
    root = get_project_root()
    pkl_path = root / "models" / "final_model_pipeline.pkl"
    joblib_path = root / "models" / "final_model_pipeline.joblib"
    if pkl_path.exists():
        return pkl_path
    if joblib_path.exists():
        return joblib_path
    return pkl_path


def load_model(model_path: Optional[Union[str, Path]] = None, reload: bool = False):
    """
    Load and cache the trained final model pipeline.

    Args:
        model_path: Optional path to serialized model file.
        reload: If True, force reload model from disk.

    Returns:
        Fitted scikit-learn Pipeline.

    Raises:
        FileNotFoundError: If model file does not exist.
    """
    global _CACHED_MODEL
    if _CACHED_MODEL is not None and not reload and model_path is None:
        return _CACHED_MODEL

    path = Path(model_path) if model_path else get_default_model_path()
    if not path.exists():
        raise FileNotFoundError(
            f"Trained model pipeline not found at {path}. Run Phase 4/5 training pipeline first."
        )

    logger.info(f"Loading final model pipeline from: {path}")
    pipeline = joblib.load(path)
    if model_path is None:
        _CACHED_MODEL = pipeline
    return pipeline


def validate_patient_input(input_data: Dict[str, Any]) -> pd.DataFrame:
    """
    Validate a dictionary of patient clinical features against the schema and bounds.

    Args:
        input_data: Dictionary mapping feature names to clinical values.

    Returns:
        Single-row pd.DataFrame with features ordered according to FEATURE_ORDER.

    Raises:
        ValueError: If required fields are missing, of invalid type, or outside supported bounds.
    """
    if not isinstance(input_data, dict):
        raise ValueError(f"Input data must be a dictionary, got {type(input_data).__name__}.")

    # Check for missing required features
    missing_fields = [f for f in FEATURE_ORDER if f not in input_data]
    if missing_fields:
        raise ValueError(f"Input validation failed. Missing required clinical fields: {missing_fields}")

    sanitized_row: Dict[str, Any] = {}

    for feat in FEATURE_ORDER:
        val = input_data[feat]
        constraints = FEATURE_CONSTRAINTS[feat]

        # Check for None / NaN
        if val is None or pd.isna(val):
            raise ValueError(f"Field '{feat}' cannot be null or NaN.")

        # Type conversion & validation
        try:
            val_num = float(val)
        except (ValueError, TypeError):
            raise ValueError(
                f"Invalid value for '{feat}': '{val}'. Expected a numeric value for {constraints['desc']}."
            )

        # Categorical set validation
        if "valid_values" in constraints:
            val_int = int(round(val_num))
            if val_int not in constraints["valid_values"]:
                raise ValueError(
                    f"Value '{val}' for '{feat}' is invalid. Supported values are {constraints['valid_values']} ({constraints['desc']})."
                )
            sanitized_row[feat] = val_int

        # Continuous range validation
        else:
            if "min" in constraints and val_num < constraints["min"]:
                raise ValueError(
                    f"Value {val_num} for '{feat}' is below the supported model validation limit ({constraints['min']})."
                )
            if "max" in constraints and val_num > constraints["max"]:
                raise ValueError(
                    f"Value {val_num} for '{feat}' exceeds the supported model validation limit ({constraints['max']})."
                )
            sanitized_row[feat] = val_num

    df_single = pd.DataFrame([sanitized_row], columns=FEATURE_ORDER)
    return df_single


def predict_risk(
    input_data: Dict[str, Any],
    model: Optional[Any] = None,
    model_path: Optional[Union[str, Path]] = None,
) -> Dict[str, Any]:
    """
    Run risk prediction for a single patient clinical profile.

    Args:
        input_data: Dictionary of clinical features.
        model: Optional pre-loaded pipeline.
        model_path: Optional path to serialized model.

    Returns:
        Structured prediction result dictionary.
    """
    # 1. Validate inputs and construct DataFrame
    df_patient = validate_patient_input(input_data)

    # 2. Load model pipeline
    pipeline = model if model is not None else load_model(model_path)

    # 3. Predict class & probabilities
    pred_class = int(pipeline.predict(df_patient)[0])
    probabilities = pipeline.predict_proba(df_patient)[0]
    p_no_disease = float(probabilities[0])
    p_disease = float(probabilities[1])

    # 4. Stratify Risk Level based on disease probability
    if p_disease >= 0.70:
        risk_level = "High Predicted Risk"
    elif p_disease >= 0.40:
        risk_level = "Moderate Predicted Risk"
    else:
        risk_level = "Low Predicted Risk"

    risk_category = "Higher Predicted Risk" if pred_class == 1 else "Lower Predicted Risk"
    confidence = float(max(probabilities))

    # 5. Extract top qualitative contributing factors
    contributing_factors = []
    if df_patient.loc[0, "thal"] == 3:
        contributing_factors.append("Reversible defect thalassemia (thal=3)")
    if df_patient.loc[0, "cp"] == 3:
        contributing_factors.append("Asymptomatic chest pain type (cp=3)")
    if df_patient.loc[0, "ca"] > 0:
        contributing_factors.append(f"{int(df_patient.loc[0, 'ca'])} major vessel(s) colored by fluoroscopy (ca>0)")
    if df_patient.loc[0, "exang"] == 1:
        contributing_factors.append("Presence of exercise-induced angina (exang=1)")
    if df_patient.loc[0, "oldpeak"] >= 2.0:
        contributing_factors.append(f"Elevated ST depression ({df_patient.loc[0, 'oldpeak']:.1f} mm)")
    if df_patient.loc[0, "thalach"] < 130:
        contributing_factors.append(f"Reduced maximum heart rate achieved ({int(df_patient.loc[0, 'thalach'])} bpm)")

    result = {
        "prediction": pred_class,
        "predicted_category": risk_category,
        "risk_level": risk_level,
        "heart_disease_probability": round(p_disease, 4),
        "heart_disease_percentage": round(p_disease * 100, 2),
        "no_disease_probability": round(p_no_disease, 4),
        "confidence_score": round(confidence, 4),
        "contributing_clinical_factors": contributing_factors,
        "input_features": df_patient.to_dict(orient="records")[0],
        "medical_disclaimer": MEDICAL_DISCLAIMER,
    }

    return result


def predict_batch(
    df: pd.DataFrame,
    model: Optional[Any] = None,
    model_path: Optional[Union[str, Path]] = None,
) -> pd.DataFrame:
    """
    Run risk prediction across a batch DataFrame.

    Args:
        df: Input DataFrame containing patient records.
        model: Optional pre-loaded pipeline.
        model_path: Optional path to serialized model.

    Returns:
        DataFrame with added prediction and probability columns.
    """
    pipeline = model if model is not None else load_model(model_path)
    results = []

    for idx, row in df.iterrows():
        try:
            row_dict = row.to_dict()
            res = predict_risk(row_dict, model=pipeline)
            results.append({
                "predicted_risk_class": res["prediction"],
                "risk_category": res["predicted_category"],
                "risk_level": res["risk_level"],
                "heart_disease_probability": res["heart_disease_probability"],
                "validation_error": None,
            })
        except Exception as e:
            results.append({
                "predicted_risk_class": np.nan,
                "risk_category": "Validation Failed",
                "risk_level": "Unknown",
                "heart_disease_probability": np.nan,
                "validation_error": str(e),
            })

    results_df = pd.DataFrame(results, index=df.index)
    output_df = pd.concat([df.copy(), results_df], axis=1)
    return output_df


